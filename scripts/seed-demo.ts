import { createClient } from "@supabase/supabase-js";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import pg from "pg";
import { demoData as d } from "../fixtures/data-demo";
import { loadLocalEnv, requireLoopback } from "./local-env";
async function main() {
loadLocalEnv();
const api = process.env.NEXT_PUBLIC_SUPABASE_URL ?? ""; const database = process.env.LOCAL_DATABASE_URL ?? "";
requireLoopback(api); requireLoopback(database);
const admin = createClient(api, process.env.SUPABASE_SERVICE_ROLE_KEY ?? "", { auth: { persistSession: false, autoRefreshToken: false } });
const file = "artifacts/m02/demo-credentials.json";
const previous = existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
const users: Record<string, {id: string; email: string; password: string}> = {};
const sql = new pg.Client({ connectionString: database }); await sql.connect();
try {
  const migration = await sql.query("select version from supabase_migrations.schema_migrations where version='20261024000100'");
  if (!migration.rowCount) throw new Error("Run npm run data:migrate first");
  for (const [role,email] of Object.entries(d.emails)) {
    const found = await sql.query("select id from auth.users where email=$1", [email]);
    if (found.rowCount) {
      if (!previous[role] || previous[role].id !== found.rows[0].id) throw new Error("Existing identity preserved: local demo credential record is missing. Use a fresh isolated test stack.");
      users[role] = previous[role];
    } else {
      const password = `Toggle-${randomBytes(24).toString("base64url")}!`;
      const { data,error } = await admin.auth.admin.createUser({ email, password, email_confirm: true });
      if (error || !data.user) throw new Error(`Local demo user creation failed (${role})`);
      users[role] = {id: data.user.id, email, password};
      mkdirSync("artifacts/m02", {recursive:true}); writeFileSync(file, JSON.stringify({...previous,...users},null,2), {mode:0o600});
    }
  }
  await sql.query("begin");
  await sql.query("insert into public.tenants(id,name) values($1,'Toggle demo studio'),($2,'Other demo studio') on conflict do nothing", [d.tenant,d.otherTenant]);
  for (const [key,user] of Object.entries(users)) {
    const tenant = key === "other" ? d.otherTenant : d.tenant;
    const role = key === "director" ? "art_director" : key === "other" ? "producer" : key === "stranger" ? "client" : key;
    await sql.query("insert into app_private.tenant_members(tenant_id,user_id,role) values($1,$2,$3) on conflict do nothing", [tenant,user.id,role]);
  }
  for (const [tenant,id,name,brand] of [[d.tenant,d.campaign,"Evening essentials","Luma"],[d.tenant,d.privateCampaign,"Private direction","Luma"],[d.otherTenant,d.otherCampaign,"Foreign campaign","Other"]]) {
    await sql.query("insert into public.campaigns(id,tenant_id,name,brand) values($1,$2,$3,$4) on conflict do nothing", [id,tenant,name,brand]);
  }
  for (const role of ["client","director"]) await sql.query("insert into app_private.campaign_members(tenant_id,campaign_id,user_id,access_role) values($1,$2,$3,$4) on conflict do nothing", [d.tenant,d.campaign,users[role].id,role === "client" ? "client" : "studio"]);
  await sql.query("commit");
  writeFileSync(file, `${JSON.stringify(users,null,2)}\n`, {mode:0o600});
  const envFile = ".env.m02.local"; const source = readFileSync(envFile,"utf8");
  if (!source.startsWith("# Generated by Toggle M02 local setup")) throw new Error("Demo seeded; existing local test environment preserved. Configure worker credentials from ignored demo-credentials.json.");
  writeFileSync(envFile, `${source.split("\n").filter((l)=>!l.startsWith("MEDIA_WORKER_")).join("\n").trim()}\nMEDIA_WORKER_EMAIL=${users.worker.email}\nMEDIA_WORKER_PASSWORD=${users.worker.password}\n`, {mode:0o600});
  console.log("Seeded local tenants, campaigns, producer/AD/client/worker identities. Passwords are only in ignored artifacts/m02/demo-credentials.json; no messages were sent.");
} finally { await sql.end(); }

}
main().catch(()=>{console.error("Local setup/validation failed. Check configuration and service status; credentials are never printed.");process.exitCode=1;});
